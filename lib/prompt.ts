/** تلميح قصير يُضاف لتعليمات النظام حسب نوع المهمة الذي حدده الموجّه. */
export function routingHint(kind: TaskKind, urls: string[] = []): string {
  switch (kind) {
    case 'web_research':
      return urls.length
        ? `\n\n# سياق التوجيه\nالموجّه صنّف الطلب كقراءة ويب. الروابط المكتشفة في رسالة المستخدم: ${urls.join(
            ' , ',
          )}. إن كانت نتائج القراءة مرفقة أدناه فاعتمد عليها؛ وإن احتجت رابطاً آخر فاستدعِ read_public_url. لا تلخّص رابطاً لم تُقرأ نتيجته.`
        : '\n\n# سياق التوجيه\nالموجّه صنّف الطلب كبحث. لا يوجد رابط في الرسالة — اطلب من المستخدم الرابط أو أجب من معرفتك مع توضيح أنك لم تتصفح الإنترنت.';
    case 'coding':
      return '\n\n# سياق التوجيه\nالموجّه صنّف الطلب كمهمة برمجية. اتبع خطوات البرمجة: خطة قصيرة ثم ملفات كاملة عبر write_project_file ثم أوامر التشغيل.';
    case 'document_analysis':
      return '\n\n# سياق التوجيه\nالموجّه صنّف الطلب كتحليل مستند. اعتمد حصراً على نص المستند المرفق أدناه، واذكر اسم الملف في ردك.';
    case 'clarification':
      return '\n\n# سياق التوجيه\nالطلب غير واضح. اطرح سؤالاً واحداً محدداً فقط، ولا تفترض تفاصيل غير مذكورة.';
    case 'confirmation_required':
      return '\n\n# سياق التوجيه\nالطلب يتضمن عملية مؤثرة. استخدم request_user_confirmation ووصّف العملية بدقة قبل أي تنفيذ. لا تنفّذ شيئاً قبل موافقة المستخدم.';
    default:
      return '';
  }
}

/** عنوان مقترح للمحادثة من أول رسالة — بلا استدعاء نموذج. */
export function deriveTitle(firstMessage: string): string {
  const clean = firstMessage.replace(/\s+/g, ' ').trim();
  if (!clean) return 'محادثة جديدة';
  const cut = clean.slice(0, 48);
  return cut.length < clean.length ? `${cut}…` : cut;
}
